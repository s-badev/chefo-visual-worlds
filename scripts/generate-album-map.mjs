import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoMercator, geoPath } from "d3-geo";

const W = 600,
  H = 400;
const world = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/countries-50m.json", import.meta.url), "utf8"),
);
const land = feature(world, world.objects.land);
const view = (lon0, lat0, lon1, lat1) =>
  geoMercator()
    .fitExtent(
      [
        [0, 0],
        [W, H],
      ],
      {
        type: "MultiPoint",
        coordinates: [
          [lon0, lat0],
          [lon1, lat0],
          [lon1, lat1],
          [lon0, lat1],
        ],
      },
    )
    .clipExtent([
      [-10, -10],
      [W + 10, H + 10],
    ]);
const eu = view(-4, 34, 37, 51);
const reg = view(22.4, 40.5, 29.7, 43.8);
const PLACES = {
  sofia: [42.7, 23.32],
  "sunny-beach": [42.69, 27.71],
  "sveti-vlas": [42.71, 27.76],
  nessebar: [42.66, 27.73],
  burgas: [42.5, 27.47],
  plovdiv: [42.14, 24.75],
  rila: [42.13, 23.34],
  tunisia: [36.81, 10.18],
  paris: [48.86, 2.35],
  lyon: [45.76, 4.84],
  istanbul: [41.01, 28.98],
  edirne: [41.68, 26.56],
  bodrum: [37.04, 27.43],
}; // [lat, lon] — трябва да съвпада с src/content/album-places.ts (тестът го пази)
const r1 = (n) => Math.round(n * 10) / 10;
const points = Object.fromEntries(
  Object.entries(PLACES).map(([slug, [lat, lon]]) => [
    slug,
    { eu: eu([lon, lat]).map(r1), reg: reg([lon, lat]).map(r1) },
  ]),
);
const out = `// GENERATED by scripts/generate-album-map.mjs — do not edit by hand.
export const MAP_VIEWBOX = { width: ${W}, height: ${H} } as const;
export const EU_LAND = ${JSON.stringify(geoPath(eu).digits(1)(land))};
export const REG_LAND = ${JSON.stringify(geoPath(reg).digits(2)(land))};
export const PLACE_POINTS: Record<string, { eu: [number, number]; reg: [number, number] }> = ${JSON.stringify(points)};
`;
writeFileSync(new URL("../src/content/album-map.generated.ts", import.meta.url), out);
